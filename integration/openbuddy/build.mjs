import { build } from "esbuild"
import { fileURLToPath } from "node:url"
import { copyFile } from "node:fs/promises"

await build({
  absWorkingDir: fileURLToPath(new URL(".", import.meta.url)),
  entryPoints: ["src/index.ts"],
  outfile: "dist/index.js",
  bundle: true,
  platform: "node",
  conditions: ["node"],
  format: "esm",
  target: "node22",
  legalComments: "linked",
  banner: { js: "// Generated by integration/openbuddy/build.mjs. Do not edit by hand.\nimport { createRequire as __openbuddyCreateRequire } from 'node:module'; const require = __openbuddyCreateRequire(import.meta.url);" },
  logLevel: "info",
})

await Promise.all(["package.json", "LICENSES.txt"].map(name =>
  copyFile(new URL(`assets/${name}`, import.meta.url), new URL(`dist/${name}`, import.meta.url))
))
